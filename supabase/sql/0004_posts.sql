-- 0004_posts.sql
-- Creates posts table and helpers for Supabase migration from Firebase.

create table if not exists public.posts (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  content text not null,
  writer_uid uuid references auth.users(id) on delete set null,
  writer_name text not null,
  type text not null default 'board',
  number bigint generated by default as identity,
  view_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_posts_created_at on public.posts (created_at desc, id desc);
create index if not exists idx_posts_writer_uid on public.posts (writer_uid);
create index if not exists idx_posts_type on public.posts (type);

create or replace function public.handle_posts_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger posts_updated_at
before update on public.posts
for each row execute procedure public.handle_posts_updated_at();

create or replace function public.increment_post_view_count(target uuid)
returns void
language sql
security definer
set search_path = public
as $$
  update public.posts
     set view_count = view_count + 1,
         updated_at = now()
   where id = target;
$$;

grant execute on function public.increment_post_view_count(uuid) to authenticated;

alter table public.posts enable row level security;

create policy "posts_select_all" on public.posts
  for select using (true);

create policy "posts_insert_self" on public.posts
  for insert with check (auth.uid() = writer_uid);

create policy "posts_update_owner" on public.posts
  for update using (auth.uid() = writer_uid);

create policy "posts_delete_owner" on public.posts
  for delete using (auth.uid() = writer_uid);
